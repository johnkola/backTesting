);

-- Chunk interval: one year, not TimescaleDB's 7-day default. This table is
-- daily-bar dominant and spans decades of history, so 7-day chunks produce
-- thousands of near-empty chunks — and every full-table scan takes a lock per
-- chunk per parallel worker, which exhausts max_locks_per_transaction ("out of
-- shared memory") on queries like the cohesion audit's series listing. Revisit
-- if this database becomes minute-bar dominant: a month is the better interval
-- once one year of one instrument stops fitting comfortably in a chunk.
SELECT create_hypertable('candles', 'timestamp',
                         chunk_time_interval => INTERVAL '1 year',
                         if_not_exists => TRUE);

-- Existing databases created before the interval change keep their 7-day
-- setting, which only ever applies to *new* chunks — this makes future ones
-- yearly. Chunks already on disk are unaffected; see the note in README's
-- "Storage compression" for the one-off migration that consolidates them.
SELECT set_chunk_time_interval('candles', INTERVAL '1 year');

-- Idempotent migration for pre-source candles tables.
DO $migrate_candles$
DECLARE
    default_source_id BIGINT;
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_name = 'candles' AND column_name = 'source_id'
    ) THEN
        SELECT id INTO default_source_id FROM data_sources WHERE name = 'default';

        ALTER TABLE candles ADD COLUMN source_id BIGINT REFERENCES data_sources(id);
        UPDATE candles SET source_id = default_source_id WHERE source_id IS NULL;
        ALTER TABLE candles ALTER COLUMN source_id SET NOT NULL;

        ALTER TABLE candles DROP CONSTRAINT IF EXISTS candles_pkey;
        ALTER TABLE candles ADD PRIMARY KEY (instrument_id, timeframe, source_id, timestamp);

        -- Old index (without source_id) is now redundant with the new PK; drop it.
        DROP INDEX IF EXISTS idx_candles_lookup;
    END IF;
END
$migrate_candles$;

-- No idx_candles_lookup. It used to be created here on
-- (instrument_id, timeframe, source_id, timestamp) — byte-for-byte the same
-- columns in the same order as the primary key above, so it was a second copy
-- of candles_pkey: 7.9 MB across 68 chunk-level indexes, plus a write cost on
-- every COPY-based import, serving no read the PK could not already answer.
--
-- The multi-source migration above had already spotted this and dropped it as
-- "redundant with the new PK"; this line then recreated it on the very next
-- statement. The unconditional drop below closes that loop for databases
-- bootstrapped before it was noticed. TimescaleDB's candles_timestamp_idx
-- stays and does the chunk exclusion.
DROP INDEX IF EXISTS idx_candles_lookup;

-- Enable native compression on the candles hypertable. The ALTER itself is
-- idempotent in TimescaleDB 2.x (re-applying with the same options is a no-op),
-- but we guard it in a DO block so schema bootstrap stays clean on every app
-- start. compress_segmentby keeps the columns we filter on (instrument, source,
-- timeframe) outside the compressed blob so range scans don't have to
-- decompress unrelated rows. compress_orderby DESC matches how the engine
-- reads (most recent first).
--
-- Re-imports of compressed chunks require explicit decompression — TimescaleDB
-- refuses INSERT ... ON CONFLICT DO UPDATE on a compressed chunk. See the
-- "Storage compression" section in the README for the recovery path.
DO $compress_candles$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM timescaledb_information.hypertables
         WHERE hypertable_name = 'candles' AND compression_enabled = true
    ) THEN
        ALTER TABLE candles SET (
            timescaledb.compress,
            timescaledb.compress_segmentby = 'instrument_id, source_id, timeframe',
            timescaledb.compress_orderby = 'timestamp DESC'
        );
    END IF;
END
$compress_candles$;

-- Auto-compress any chunk older than 7 days. Re-importing data inside the 7-day
-- window stays cheap; older data gets compressed (typically 10-20x) and becomes
-- read-mostly. Bumped via add_compression_policy(..., if_not_exists => TRUE) so
-- repeated schema bootstraps don't error.
SELECT add_compression_policy('candles', INTERVAL '7 days', if_not_exists => TRUE);

-- Multi-timeframe rollups previously lived here as TimescaleDB continuous
-- aggregates (candles_weekly + candles_monthly). They're now produced
-- on demand by the Python loader's /api/aggregate endpoint and written
-- back into `candles` at the target timeframe, so all multi-tf reads go
-- through one table and bootstrap doesn't need a TimescaleDB-only feature.
-- The migration below drops the views if a previously-bootstrapped DB
-- still has them; harmless on a fresh schema.
DROP MATERIALIZED VIEW IF EXISTS candles_weekly CASCADE;
DROP MATERIALIZED VIEW IF EXISTS candles_monthly CASCADE;

