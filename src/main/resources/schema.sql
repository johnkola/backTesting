CREATE TABLE IF NOT EXISTS candles (
    id BIGSERIAL,
    instrument_id BIGINT NOT NULL REFERENCES instruments(id),
    source_id BIGINT NOT NULL REFERENCES data_sources(id),
    timeframe VARCHAR(10) NOT NULL,
    timestamp TIMESTAMPTZ NOT NULL,
    open DOUBLE PRECISION NOT NULL,
    high DOUBLE PRECISION NOT NULL,
    low DOUBLE PRECISION NOT NULL,
    close DOUBLE PRECISION NOT NULL,
    volume DOUBLE PRECISION DEFAULT 0,
    PRIMARY KEY (instrument_id, timeframe, source_id, timestamp)
);

SELECT create_hypertable('candles', 'timestamp', if_not_exists => TRUE);

-- Idempotent migration for pre-source candles tables.
DO $migrate_candles$
DECLARE
    default_source_id BIGINT;
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_name = 'candles' AND column_name = 'source_id'
    ) THEN
        SELECT id INTO default_source_id FROM data_sources WHERE name = 'default';

        ALTER TABLE candles ADD COLUMN source_id BIGINT REFERENCES data_sources(id);
        UPDATE candles SET source_id = default_source_id WHERE source_id IS NULL;
        ALTER TABLE candles ALTER COLUMN source_id SET NOT NULL;

        ALTER TABLE candles DROP CONSTRAINT IF EXISTS candles_pkey;
        ALTER TABLE candles ADD PRIMARY KEY (instrument_id, timeframe, source_id, timestamp);

        -- Old index (without source_id) is now redundant with the new PK; drop it.
        DROP INDEX IF EXISTS idx_candles_lookup;
    END IF;
END
$migrate_candles$;

CREATE INDEX IF NOT EXISTS idx_candles_lookup ON candles(instrument_id, timeframe, source_id, timestamp);

-- Enable native compression on the candles hypertable. The ALTER itself is
-- idempotent in TimescaleDB 2.x (re-applying with the same options is a no-op),
-- but we guard it in a DO block so schema bootstrap stays clean on every app
-- start. compress_segmentby keeps the columns we filter on (instrument, source,
-- timeframe) outside the compressed blob so range scans don't have to
-- decompress unrelated rows. compress_orderby DESC matches how the engine
-- reads (most recent first).
--
-- Re-imports of compressed chunks require explicit decompression — TimescaleDB
-- refuses INSERT ... ON CONFLICT DO UPDATE on a compressed chunk. See the
-- "Storage compression" section in the README for the recovery path.
DO $compress_candles$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM timescaledb_information.hypertables
         WHERE hypertable_name = 'candles' AND compression_enabled = true
    ) THEN
        ALTER TABLE candles SET (
            timescaledb.compress,
            timescaledb.compress_segmentby = 'instrument_id, source_id, timeframe',
            timescaledb.compress_orderby = 'timestamp DESC'
        );
    END IF;
END
$compress_candles$;

-- Auto-compress any chunk older than 7 days. Re-importing data inside the 7-day
-- window stays cheap; older data gets compressed (typically 10-20x) and becomes
-- read-mostly. Bumped via add_compression_policy(..., if_not_exists => TRUE) so
-- repeated schema bootstraps don't error.
SELECT add_compression_policy('candles', INTERVAL '7 days', if_not_exists => TRUE);

-- Continuous aggregates: W1 + M1 rollups computed lazily from D1 candles by
-- TimescaleDB. No engine or web layer reads them today — they're here so a
-- future multi-timeframe consumer (e.g. a `run -t W1` fallback when no W1
-- candles were imported, or a multi-TF chart in the web UI) can read W1/M1
-- bars without re-aggregating client-side. The materialized data sits next
-- to the hypertable and the refresh policies keep it current.
--
-- WHERE timeframe='D1' so a user separately importing W1/M1 CSVs into the
-- same candles table doesn't double-count. FIRST/LAST take the open at the
-- earliest D1 in the bucket and the close at the latest, which is the
-- standard rollup semantics.
--
-- CREATE MATERIALIZED VIEW IF NOT EXISTS is the standard PostgreSQL idiom;
-- TimescaleDB inherits it so repeated schema bootstraps are no-ops once the
-- views exist.
CREATE MATERIALIZED VIEW IF NOT EXISTS candles_weekly
    WITH (timescaledb.continuous) AS
    SELECT instrument_id,
           source_id,
           time_bucket(INTERVAL '7 days', timestamp) AS bucket,
           FIRST(open, timestamp) AS open,
           MAX(high)              AS high,
           MIN(low)               AS low,
           LAST(close, timestamp) AS close,
           SUM(volume)            AS volume
      FROM candles
     WHERE timeframe = 'D1'
     GROUP BY instrument_id, source_id, bucket
    WITH NO DATA;

CREATE MATERIALIZED VIEW IF NOT EXISTS candles_monthly
    WITH (timescaledb.continuous) AS
    SELECT instrument_id,
           source_id,
           time_bucket(INTERVAL '1 month', timestamp) AS bucket,
           FIRST(open, timestamp) AS open,
           MAX(high)              AS high,
           MIN(low)               AS low,
           LAST(close, timestamp) AS close,
           SUM(volume)            AS volume
      FROM candles
     WHERE timeframe = 'D1'
     GROUP BY instrument_id, source_id, bucket
    WITH NO DATA;

-- Refresh policies. Weekly: catch anything in the last 90 days, leave a 1-day
-- gap so we don't refight with in-flight imports; hourly cadence. Monthly:
-- catch the last year, 7-day gap, every 12 hours (changes slowly).
SELECT add_continuous_aggregate_policy('candles_weekly',
    start_offset      => INTERVAL '90 days',
    end_offset        => INTERVAL '1 day',
    schedule_interval => INTERVAL '1 hour',
    if_not_exists     => TRUE);

SELECT add_continuous_aggregate_policy('candles_monthly',
    start_offset      => INTERVAL '365 days',
    end_offset        => INTERVAL '7 days',
    schedule_interval => INTERVAL '12 hours',
    if_not_exists     => TRUE);

CREATE TABLE IF NOT EXISTS data_imports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id BIGINT NOT NULL REFERENCES data_sources(id),
    instrument_id BIGINT NOT NULL REFERENCES instruments(id),
    timeframe VARCHAR(10) NOT NULL,
    file_path TEXT NOT NULL,
    file_name TEXT NOT NULL,
    row_count INT NOT NULL,
    imported_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_data_imports_source ON data_imports(source_id, imported_at DESC);

